def build_swot(filename: str, *, copy: bool = False) -> None:
    doc = Document()
    setup(doc)
    title(doc, "Таблица 1.3 — SWOT-анализ проекта «ЭкоНорма BY»")

    table = doc.add_table(rows=2, cols=2)
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = True

    for cell, (header, items) in zip(table.rows[0].cells + table.rows[1].cells, SWOT):
        p = cell.paragraphs[0]
        run = p.add_run(header)
        run.bold = True
        run.font.size = Pt(14)
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        for item in items:
            bp = cell.add_paragraph(style="List Bullet")
            bp.add_run(item)
            bp.paragraph_format.space_after = Pt(2)

        if copy:
            # Рабочая копия: сохранены те же блоки, но с характерными
            # «черновыми» повторами, как в файле-примере.
            if header == "Сильные стороны":
                extra = [
                    "Глубокая локализация под РБ: база вопросов создаётся с учётом "
                    "актуальных требований законодательства РБ.",
                    "Низкая платежеспособность ниши: средний чек ограничен "
                    "бюджетом малых организаций.",
                ]
            elif header == "Угрозы":
                extra = ["-"]
            else:
                extra = []
            for item in extra:
                bp = cell.add_paragraph(style="List Bullet")
                bp.add_run(item)
                bp.paragraph_format.space_after = Pt(2)

    doc.add_paragraph()
    p = doc.add_paragraph()
    p.add_run(
        "Вывод: проект сочетает сильную локализацию под белорусское законодательство "
        "с низкой ценой и простотой внедрения. Ключевые риски — инертность МСБ и "
        "необходимость постоянно поддерживать актуальность базы нормативных "
        "документов; они компенсируются прямыми продажами и работой эксперта."
        if not copy
        else
        "Вывод: проект сочетает сильную локализацию и низкую цену. Ключевые риски — "
        "инертность МСБ и актуальность базы нормативных документов."
    )
    for run in p.runs:
        run.italic = True

    doc.save(OUT / filename)


